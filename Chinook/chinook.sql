CREATE TABLE dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL,
    day_of_month SMALLINT NOT NULL,
    day_name VARCHAR(20) NOT NULL,
    week_number SMALLINT NOT NULL,
    month_number SMALLINT NOT NULL,
    month_name VARCHAR(20) NOT NULL,
    quarter SMALLINT NOT NULL,
    year SMALLINT NOT NULL
);

CREATE TABLE dim_customer (
    customer_key INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_id INTEGER NOT NULL UNIQUE,
    first_name VARCHAR(40) NOT NULL,
    last_name VARCHAR(20) NOT NULL,
    company VARCHAR(80),
    city VARCHAR(40),
    state VARCHAR(40),
    country VARCHAR(40),
    postal_code VARCHAR(10)
);

CREATE TABLE dim_track (
    track_key INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    track_id INTEGER NOT NULL UNIQUE,
    track_name VARCHAR(200) NOT NULL,
    composer VARCHAR(220),
    album_title VARCHAR(160),
    artist_name VARCHAR(120),
    genre_name VARCHAR(120),
    media_type_name VARCHAR(120),
    milliseconds INTEGER NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL
);

CREATE TABLE dim_employee (
    employee_key INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    employee_id INTEGER NOT NULL UNIQUE,
    first_name VARCHAR(20) NOT NULL,
    last_name VARCHAR(20) NOT NULL,
    title VARCHAR(30),
    hire_date DATE,
    manager_name VARCHAR(60)
);

CREATE TABLE dim_playlist (
    playlist_key INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    playlist_id INTEGER NOT NULL UNIQUE,
    playlist_name VARCHAR(120)
);

CREATE TABLE bridge_track_playlist (
    track_key INTEGER NOT NULL,
    playlist_key INTEGER NOT NULL,
    PRIMARY KEY (track_key, playlist_key),
    FOREIGN KEY (track_key) REFERENCES dim_track (track_key),
    FOREIGN KEY (playlist_key) REFERENCES dim_playlist (playlist_key)
);

CREATE TABLE fact_invoice_line (
    invoice_line_id BIGINT PRIMARY KEY,
    invoice_id INTEGER NOT NULL,
    customer_key INTEGER NOT NULL,
    track_key INTEGER NOT NULL,
    employee_key INTEGER,
    date_key INTEGER NOT NULL,
    quantity SMALLINT NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL,
    line_total NUMERIC(10,2) NOT NULL,
    FOREIGN KEY (customer_key) REFERENCES dim_customer (customer_key),
    FOREIGN KEY (track_key) REFERENCES dim_track (track_key),
    FOREIGN KEY (employee_key) REFERENCES dim_employee (employee_key),
    FOREIGN KEY (date_key) REFERENCES dim_date (date_key)
);

CREATE INDEX fact_invoice_line_track_idx ON fact_invoice_line (track_key);
CREATE INDEX fact_invoice_line_date_idx ON fact_invoice_line (date_key);
